    pub fn pluralize_tracks(&self, count: usize) -> String {
        match self.lang {
            Language::English => {
                if count == 1 {
                    "track".to_string()
                } else {
                    "tracks".to_string()
                }
            }
            Language::Polish => {
                if count == 1 {
                    "utwór".to_string()
                } else if count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 10 || count % 100 >= 20) {
                    "utwory".to_string()
                } else {
                    "utworów".to_string()
                }
            }
        }
    }
